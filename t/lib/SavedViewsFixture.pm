package SavedViewsFixture;
use Mojo::Base -base, -signatures;
use DBI ();
use Selecto;
use Mojo::URL ();
use Selecto::Components::Config ();
use Selecto::Components::SavedQueryStore::Domains ();

sub new ($class, $backend = 'sqlite', $url = undef) {
    my $dbh;
    if ($backend eq 'sqlite') {
        $dbh = DBI->connect('dbi:SQLite:dbname=:memory:', '', '', {RaiseError => 1, PrintError => 0});
        $dbh->do('PRAGMA foreign_keys = ON');
    } else {
        my $parsed = Mojo::URL->new($url);
        die 'fixture requires the RAM server' unless $parsed->host eq '127.0.0.1' && $parsed->port == 55448;
        $dbh = DBI->connect('dbi:Pg:dbname=' . substr($parsed->path, 1) . ';host=127.0.0.1;port=55448',
            $parsed->username, $parsed->password, {RaiseError => 1, PrintError => 0});
    }
    my $adapter = Selecto->adapter($backend => (dbh => $dbh));
    my @sources;
    for my $name (qw(personal company role_link dashboard_tile)) {
        my $table = "sv_$name";
        $dbh->do("DROP TABLE IF EXISTS $table");
        my $id = $backend eq 'sqlite' ? 'INTEGER PRIMARY KEY' : 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
        $dbh->do("CREATE TABLE $table (id $id, owner_id INTEGER NOT NULL, name VARCHAR(255) NOT NULL,
            url TEXT, folder VARCHAR(100), parent_id INTEGER REFERENCES $table(id) ON DELETE RESTRICT,
            kind VARCHAR(20) DEFAULT 'view', created_by INTEGER, modified_by INTEGER,
            schedule VARCHAR(100) DEFAULT 'weekly', official INTEGER DEFAULT 1, UNIQUE(owner_id, name))");
        my %types = (id => 'integer', owner_id => 'integer', name => 'string', url => 'string', folder => 'string',
            parent_id => 'integer', kind => 'string', created_by => 'integer', modified_by => 'integer',
            schedule => 'string', official => 'integer');
        push @sources, {name => $name, scope => $name eq 'personal' ? 'user' : $name eq 'company' ? 'client' : 'priv',
            target_label => ucfirst($name), fields => {key => 'id', name => 'name', url => 'url',
                ($name eq 'role_link' ? (folder => 'folder', parent => 'parent_id', kind => 'kind') : ())},
            ($name eq 'role_link' ? (explorer_filter => sub ($row, $ctx, $config, @rest) {
                return ($row->{kind} // '') eq 'folder' || Selecto::Components::SavedView::_local_view($config, Mojo::URL->new($row->{url} // ''));
            }) : ()),
            write_check => sub ($ctx, $config, $op, $row, @rest) {
                return 0 if $ctx->{deny_source} && $ctx->{deny_source} eq $name;
                return 0 if $ctx->{deny_row} && $row && $row->{name} eq $ctx->{deny_row};
                return 1;
            },
            engine_factory => sub ($ctx, @rest) {
                my $domain = Selecto::Domain->parse({name => 'SavedPanels',
                    source => {source_table => $table, primary_key => 'id', fields => [sort keys %types],
                        columns => {map { $_ => {type => $types{$_}} } keys %types}, associations => {}},
                    writes => {operations => {map { $_ => {enabled => 1, returning => 'all'} } qw(insert update delete)},
                        fields => {map { $_ => {insertable => 1, updatable => 1} } qw(name url folder parent_id kind)},
                        row_revision => $ctx->{column_revision}
                            ? {column => 'official', required => JSON::PP::true}
                            : {columns => [sort keys %types], required => JSON::PP::true},
                        host_bound_fields => {owner_id => {mode => 'owner', source => ['context', 'owner']},
                            created_by => {mode => 'created_by', source => ['context', 'actor']},
                            modified_by => {mode => 'modified_by', source => ['context', 'actor']}},
                        unique_keys => {owner_name => [qw(owner_id name)]}}});
                $domain = $domain->with_required_predicate(Selecto::Expression->eq('owner_id', $ctx->{owner} // 11));
                return Selecto::Engine->new(domain => $domain, adapter => $adapter,
                    write_context => {owner => $ctx->{owner} // 11, actor => $ctx->{actor} // 101});
            }};
    }
    # Explorer always uses its own in-memory engine. PostgreSQL-backed saved
    # sources therefore exercise the different-engine contract directly.
    my $explorer_dbh = DBI->connect('dbi:SQLite:dbname=:memory:', '', '', {RaiseError => 1, PrintError => 0});
    $explorer_dbh->do('CREATE TABLE orders (id INTEGER PRIMARY KEY, order_ref TEXT, piece_count INTEGER, contact_email TEXT, received_on TEXT)');
    my $config = Selecto::Components::Config->new(id => 'orders', title => 'Orders', path => '/explore/orders',
        default_fields => ['order_ref'], default_group => ['order_ref'],
        engine_factory => sub ($ctx) {
            my $domain = Selecto::Domain->parse({name => 'Orders', source => {source_table => 'orders', primary_key => 'id',
                fields => [qw(id order_ref piece_count contact_email received_on)], associations => {}, columns => {
                    id => {type => 'integer'}, order_ref => {type => 'string', name => 'Order reference'},
                    piece_count => {type => 'integer'}, received_on => {type => 'date'},
                    contact_email => {type => 'string', ($ctx->{private} ? (internal => 1) : ())}}}});
            Selecto::Engine->new(domain => $domain, adapter => Selecto->adapter(sqlite => (dbh => $explorer_dbh)));
        });
    my $store = Selecto::Components::SavedQueryStore::Domains->new(sources => \@sources);
    $config->saved_query_store($store);
    return bless {dbh => $dbh, explorer_dbh => $explorer_dbh, store => $store, config => $config, sources => \@sources}, $class;
}
sub cleanup ($self) {
    $self->{dbh}->do('DELETE FROM sv_role_link WHERE parent_id IS NOT NULL');
    $self->{dbh}->do('DELETE FROM sv_role_link');
    $self->{dbh}->do("DROP TABLE sv_$_") for qw(personal company role_link dashboard_tile);
}
1;
